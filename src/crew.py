def build_crew(topic: str, output_path: str = None) -> tuple:
    """
    Constructs the CrewAI multi-agent crew with research, writing, and review agents.
    """
    llm = get_configured_llm()
    
    # Instantiate specialized agents
    research_agent = create_research_agent(llm=llm)
    writer_agent = create_writer_agent(llm=llm)
    reviewer_agent = create_reviewer_agent(llm=llm)

    # Instantiate tasks with sequential dependencies
    research_task = create_research_task(agent=research_agent, topic=topic)
    writing_task = create_writing_task(agent=writer_agent, topic=topic, context_tasks=[research_task])
    review_task = create_review_task(agent=reviewer_agent, topic=topic, context_tasks=[writing_task], output_filename=output_path)

    # Assemble Crew
    crew = Crew(
        agents=[research_agent, writer_agent, reviewer_agent],
        tasks=[research_task, writing_task, review_task],
        process=Process.sequential,
        verbose=True
    )

    return crew, (research_agent, writer_agent, reviewer_agent), (research_task, writing_task, review_task)

def run_research_pipeline(topic: str, output_path: str = None, force_demo: bool = False) -> str:
    """
    Executes the research and report generation pipeline.
    Uses real CrewAI LLM kickoff if an API key is present and force_demo is False;
    otherwise uses the robust simulation mode.
    """
    if force_demo or not has_active_llm_key():
        return run_simulation(topic, output_path)

    try:
        crew, _, _ = build_crew(topic=topic, output_path=output_path)
        print(f"\n[CrewAI] Starting autonomous agent kickoff for topic: '{topic}'...")
        result = crew.kickoff(inputs={"topic": topic})
        report_str = str(result)
        
        if output_path:
            out_file = Path(output_path)
            out_file.parent.mkdir(parents=True, exist_ok=True)
            out_file.write_text(report_str, encoding="utf-8")
            print(f"[✓] Final report saved to: {out_file.resolve()}")
            
        return report_str
    except Exception as e:
        print(f"\n[Warning] Live Crew execution encountered an issue ({e}). Running fallback pipeline...")
        return run_simulation(topic, output_path)
